    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        jTextField3.setText("");
        jTextField5.setText("");
        
        int idGet = Integer.parseInt(jTextField7.getText());
        int id = -1;
        for(int i=0;i<n;i++){
            if(idGet == ids[i]){
                id = i;
                break;
            }
        }
        if(id > -1){
            int order = 0;
            int point = points[id];
            for (int i = 0; i < n; i++) {
                if (point < points[i] ) {
                    order++;
                }
            }
            jTextField3.setText(gradeList[id]);
            jTextField5.setText(++order +"");
        }
    }//GEN-LAST:event_jButton3ActionPerformed

