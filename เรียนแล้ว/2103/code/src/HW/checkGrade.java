    private String calGrade(int point){
        String grade = "";
        if(point < 50){
            grade = "F";
        }else if(point < 60){
            grade = "C";
        }else if(point < 70){
            grade = "B";
        }else{
            grade = "A";
        }
        return grade;
    }
    
    private void addPoint(int id, int point, String grade){
        if(n == 0){
            ids[0] = id;
            points[0] = point;
            gradeList[0] = grade;
            n++;
        }else{
            for(int i = 0;i<n;i++){
                if(ids[i] == id){
                    ids[i] = id;
                    points[i] = points[i] + point;
                    gradeList[i] = calGrade(points[i]);
                    return;
                }else if(ids[i] > id){
                    int j = n-1;
                    while(j>=i){
                        ids[j+1]=ids[j];
                        points[j+1]=points[j];
                        gradeList[j+1]=gradeList[j];
                        j--;
                    }
                    ids[i] = id;
                    points[i] = point;
                    gradeList[i] = grade;
                    n++;
                    return;
                }
            }
            //id มากกว่าทุกค่าที่มีมา
            ids[n] = id;
            points[n] = point;
            gradeList[n] = grade;
            n++;
        }
    }
    
    private void showAll(){
        String dataShow = "";
        if(n > 0){
            dataShow = " id  point ( grades ) ";
            dataShow += "\n " +  ids[0] + " :: " + points[0] + " (" + gradeList[0] + ")";
        }
        for(int i=1;i<n;i++){
            dataShow += "\n " +  ids[i] + " ::: " + points[i] + " (" + gradeList[i] + ")";
        }
        jTextArea1.setText(dataShow);
        showN();
    }
    
    private void showN(){
        jTextField4.setText("N : " + n);
    }
    
    private void delete(int id){
        
        for(int i=0;i<n;i++){
            if(ids[i] == id){
                int index = i;
                while(index < n){
                    ids[index] = ids[index+1];
                    points[index] = points[index+1];
                    gradeList[index] = gradeList[index+1];
                    index++;
                }
                n--;
                break;
            }
        }
        
    }
            
